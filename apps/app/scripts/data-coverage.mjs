#!/usr/bin/env node
/**
 * Where every screen's data comes from.
 *
 *   node apps/app/scripts/data-coverage.mjs           report, and rewrite src/lib/coverage.generated.ts
 *   node apps/app/scripts/data-coverage.mjs --check   fail when that file is stale or a collection is unclassified
 *   node apps/app/scripts/data-coverage.mjs --json    machine-readable report
 *
 * A collection is LIVE when `src/server/sources/<area>.ts` declares a source for it (read from server/api),
 * STATIC when the data map classes it as product configuration that stays in code, and SAMPLE otherwise
 * (served by the embedded fixture store). The shell marks every screen that still draws a sample collection.
 * The data map (`packages/data/src/data-map.json`) is the register of what each collection is and where its
 * data belongs in Postgres.
 */
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const app = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const repo = path.resolve(app, "../..");
const args = new Set(process.argv.slice(2));

const map = JSON.parse(readFileSync(path.join(repo, "packages/data/src/data-map.json"), "utf8"));
const byName = new Map(map.map((r) => [r.collection, r]));

function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    const p = path.join(dir, name);
    if (statSync(p).isDirectory()) walk(p, out);
    else out.push(p);
  }
  return out;
}

// Live sources: the quoted keys of each area's defineSources({...}).
const live = new Set();
const liveFiles = {};
for (const file of walk(path.join(app, "src/server/sources")).filter((f) => /\.ts$/.test(f))) {
  const text = readFileSync(file, "utf8");
  if (!text.includes("defineSources(")) continue;
  for (const m of text.matchAll(/^\s*"([a-z]+\.[A-Za-z0-9]+)"\s*:/gm)) {
    live.add(m[1]);
    liveFiles[m[1]] = path.relative(app, file).replace(/\\/g, "/");
  }
}

// Pages: the board each one gates on and the collections it reads (every "<area>.<thing>" literal).
const areas = new Set(map.map((r) => r.area));
const pages = [];
for (const file of walk(path.join(app, "src/app")).filter((f) => /[\\/]page\.tsx$/.test(f))) {
  const text = readFileSync(file, "utf8");
  const board = text.match(/require(?:Persona|Screen)\(\s*"([A-Za-z0-9]+)"/)?.[1] ?? null;
  const literals = [...text.matchAll(/"([a-z]+)\.([A-Za-z0-9]+)"/g)]
    .filter((m) => areas.has(m[1]))
    .map((m) => `${m[1]}.${m[2]}`);
  pages.push({
    route: path.relative(path.join(app, "src/app"), path.dirname(file)).replace(/\\/g, "/"),
    board,
    collections: [...new Set(literals)],
  });
}

const problems = [];
const statusOf = (name) => (live.has(name) ? "live" : byName.get(name)?.class === "static" ? "static" : "sample");
for (const p of pages) {
  for (const c of p.collections)
    if (!byName.has(c)) problems.push(`${p.route} reads "${c}", which the data map does not classify`);
}
for (const name of live) {
  if (!byName.has(name))
    problems.push(`live source "${name}" (${liveFiles[name]}) is not a collection in the data map`);
}

const read = new Set(pages.flatMap((p) => p.collections));
const totals = { live: 0, static: 0, sample: 0 };
const byArea = {};
for (const r of map) {
  const s = statusOf(r.collection);
  totals[s]++;
  byArea[r.area] ??= { live: 0, static: 0, sample: 0 };
  byArea[r.area][s]++;
}

// Per board: how many sample collections the screen still draws (0 = fully real or static).
const sampleByBoard = {};
for (const p of pages) {
  if (!p.board) continue;
  const sample = p.collections.filter((c) => statusOf(c) === "sample").length;
  sampleByBoard[p.board] = (sampleByBoard[p.board] ?? 0) + sample;
}
const boards = Object.keys(sampleByBoard).sort();
const liveBoards = boards.filter((b) => sampleByBoard[b] === 0);

const generated = `// Generated by scripts/data-coverage.mjs from the data map, the live sources and the pages. Do not edit.
// Sample collections each screen still draws from the fixture store; 0 means every collection is live or static.
export const sampleCollectionsByBoard: Record<string, number> = {
${boards.map((b) => `  ${b}: ${sampleByBoard[b]},`).join("\n")}
};
`;
const target = path.join(app, "src/lib/coverage.generated.ts");
let current = "";
try {
  current = readFileSync(target, "utf8").replace(/\r\n/g, "\n");
} catch {}

if (args.has("--json")) {
  console.log(JSON.stringify({ totals, byArea, live: [...live].sort(), sampleByBoard, problems }, null, 1));
} else {
  console.log(`collections: ${map.length} (read by pages: ${read.size})`);
  console.log(`live ${totals.live} · static ${totals.static} · sample ${totals.sample}`);
  console.log(`screens: ${boards.length}, fully off sample data: ${liveBoards.length}`);
  for (const [area, t] of Object.entries(byArea))
    console.log(
      `  ${area.padEnd(12)} live ${String(t.live).padStart(3)}  static ${String(t.static).padStart(3)}  sample ${String(t.sample).padStart(3)}`,
    );
}
for (const p of problems) console.error(`PROBLEM ${p}`);

if (args.has("--check")) {
  if (problems.length) process.exit(1);
  if (current !== generated) {
    console.error("src/lib/coverage.generated.ts is stale: run node apps/app/scripts/data-coverage.mjs");
    process.exit(1);
  }
  console.log(`COVERAGE CURRENT live=${totals.live} static=${totals.static} sample=${totals.sample}`);
} else {
  if (current !== generated) writeFileSync(target, generated);
  if (problems.length) process.exit(1);
}
