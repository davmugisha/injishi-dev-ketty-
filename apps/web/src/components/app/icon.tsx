export function Icon({
  name,
  className = "w-5 h-5",
  style,
}: {
  name: string;
  className?: string;
  style?: React.CSSProperties;
}) {
  // An unknown name renders the help mark rather than a hole in the layout,
  // which is what the old runtime did and what call sites still rely on.
  const Glyph = ICONS[name] ?? ICONS["circle-help"];
  return <Glyph className={className} style={style} aria-hidden="true" />;
}
