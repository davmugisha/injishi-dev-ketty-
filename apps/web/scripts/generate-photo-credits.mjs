/**
 * Generate the photo credits page data from the image manifest.
 *
 * Nearly every photograph the site ships is CC BY or CC BY-SA (the script
 * prints the exact count), which oblige us to name the author and the licence
 * wherever the work appears. Shipping them uncredited would be a licence breach, so the
 * credit list is generated from the same manifest the encoder reads — there is
 * no way to add a photograph to the site without it appearing here.
 *
 *   node scripts/generate-photo-credits.mjs
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";

/**
 * Carried from the donor tree by ADR-015 build step 3. Its paths are rewritten
 * for this home: `scripts/` sits inside `apps/web`, so ROOT is the app rather
 * than a monorepo root, the manifest is `scripts/photo-manifest.json`, and the
 * originals land in `scripts/sourced/` — OUTSIDE `public/`, so a refresh cannot
 * push the committed tree over the `pnpm assets:check` ceiling.
 */
const ROOT = path.resolve(import.meta.dirname, "..");
const MANIFEST = path.join(ROOT, "scripts/photo-manifest.json");
const OUT = path.join(ROOT, "src/data/generated/photo-credits.ts");

const entries = JSON.parse(readFileSync(MANIFEST, "utf8"));

// Commons author fields can carry newlines and markup remnants — a derivative
// work credits both photographers on separate lines — so whitespace is
// collapsed as well as quotes escaped, or the emitted string literal breaks.
const esc = (s) =>
  String(s ?? "")
    .replace(/\s+/g, " ")
    .trim()
    .replace(/\\/g, "\\\\")
    .replace(/"/g, '\\"');

// Counted here, before the template, so the prose in the generated file and
// the summary line below can never disagree with the manifest they describe.
const needing = entries.filter((e) => e.attribution_required).length;
const standIns = entries.filter((e) => !e.depicts_actual_property).length;

const rows = entries
  .slice()
  .sort((a, b) => a.subject.localeCompare(b.subject) || a.file.localeCompare(b.file))
  .map(
    (e) => `  {
    stem: "${esc(e.file.replace(/\.[^.]+$/, ""))}",
    subject: "${esc(e.subject)}",
    author: "${esc(e.author)}",
    licence: "${esc(e.licence)}",
    sourceUrl: "${esc(e.source_url)}",
    attributionRequired: ${e.attribution_required ? "true" : "false"},
    depictsActualProperty: ${e.depicts_actual_property ? "true" : "false"},
  },`,
  )
  .join("\n");

const file = `// Generated by scripts/generate-photo-credits.mjs. Do not edit by hand.
//
// Every photograph the site ships, with the author and licence Wikimedia
// Commons publishes for it. Most are CC BY or CC BY-SA, which require the
// credit to travel with the work — so this list is generated from the image
// manifest rather than maintained separately, and a photograph cannot reach
// the site without reaching this page.

export interface PhotoCredit {
  stem: string;
  subject: string;
  author: string;
  licence: string;
  sourceUrl: string;
  attributionRequired: boolean;
  /**
   * Whether this photograph shows the property it illustrates.
   *
   * False for ${standIns} of the ${entries.length}: they are Rwandan landscape and city photography
   * standing in for a stay whose own pictures we do not hold. A card that shows
   * one without saying so implies the guest is looking at the place they would
   * book. So a photograph with this flag false carries a VISIBLE credit where
   * it appears, not only on the credits page (ADR-015 call 5).
   */
  depictsActualProperty: boolean;
}

export const PHOTO_CREDITS: PhotoCredit[] = [
${rows}
];
`;

mkdirSync(path.dirname(OUT), { recursive: true });
writeFileSync(OUT, file);

console.log(
  `${entries.length} credits written (${needing} require attribution, ` +
    `${standIns} do not depict the property they illustrate).`,
);
