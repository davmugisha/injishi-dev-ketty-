#!/usr/bin/env node
/**
 * The phone's icon glyphs, generated (mobile spec 0002, D-n, AC-10).
 *
 *   pnpm --filter @injishi/mobile icons:gen     # writes src/components/ui/icon-glyphs.ts
 *   pnpm --filter @injishi/mobile icons:check   # fails when that file is stale, or a name in use is not listed
 *
 * The names live in `src/components/ui/icons.json`. A name is the PascalCase of its file name in
 * `@gravity-ui/icons/svgs` (`arrow-rotate-right.svg` is `ArrowRotateRight`, `boxes-3.svg` is
 * `Boxes3`); a name with no SVG fails. A new icon is one line in icons.json, then `icons:gen`.
 *
 * Each glyph keeps its own view box (two of Gravity's are 17 wide) and its paths in order. A
 * `<g>`'s fill rule passes down to its paths. The full box clip path some files carry clips
 * nothing and is dropped. A path with a fixed colour (the red dot of `comments-dot.svg`) is drawn in
 * the icon's tone like every other path, as the screens drew it before, so no colour literal
 * reaches `src`.
 *
 * The output is byte identical for the same inputs: names sorted, LF line endings.
 */

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const APP_DIR = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const NAMES_FILE = path.join(APP_DIR, "src", "components", "ui", "icons.json");
const OUT_FILE = path.join(APP_DIR, "src", "components", "ui", "icon-glyphs.ts");
const SRC_DIR = path.join(APP_DIR, "src");

const require = createRequire(path.join(APP_DIR, "package.json"));
const GRAVITY_DIR = path.dirname(require.resolve("@gravity-ui/icons/package.json"));
const SVG_DIR = path.join(GRAVITY_DIR, "svgs");
const GRAVITY_VERSION = JSON.parse(readFileSync(path.join(GRAVITY_DIR, "package.json"), "utf8")).version;

/** `arrow-rotate-right` -> `ArrowRotateRight`, `boxes-3` -> `Boxes3`. */
export function pascalName(fileName) {
  return fileName
    .replace(/\.svg$/, "")
    .split("-")
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("");
}

function attributes(tag) {
  const out = {};
  for (const [, name, value] of tag.matchAll(/([a-zA-Z-]+)="([^"]*)"/g)) out[name] = value;
  return out;
}

/** One SVG as `{ size, paths: [{ d, evenodd }] }`. Throws on anything this generator does not draw. */
export function parseSvg(svg, label = "svg") {
  const viewBox = attributes(svg.match(/<svg\b[^>]*>/)?.[0] ?? "")
    .viewBox?.split(/\s+/)
    .map(Number);
  if (viewBox?.[0] !== 0 || viewBox[1] !== 0 || viewBox[2] !== viewBox[3]) {
    throw new Error(`${label}: expected a square view box from 0 0, got ${viewBox?.join(" ") ?? "none"}`);
  }
  const body = svg.replace(/<defs>[\s\S]*?<\/defs>/g, "");
  const groups = [];
  const paths = [];
  for (const [tag] of body.matchAll(/<\/?[a-zA-Z]+\b[^>]*>/g)) {
    if (tag.startsWith("</g")) {
      groups.pop();
      continue;
    }
    const name = tag.match(/^<\/?([a-zA-Z]+)/)[1];
    if (name === "svg") continue;
    const own = attributes(tag);
    if (name === "g") {
      groups.push(own);
      continue;
    }
    if (name !== "path") throw new Error(`${label}: unexpected <${name}>`);
    const inherited = Object.assign({}, ...groups, own);
    if (!own.d) throw new Error(`${label}: a <path> without d`);
    paths.push({ d: own.d, evenodd: inherited["fill-rule"] === "evenodd" });
  }
  if (paths.length === 0) throw new Error(`${label}: no paths`);
  return { size: viewBox[2], paths };
}

/** PascalCase name -> SVG file name, for every icon the package ships. */
function svgIndex() {
  const index = new Map();
  for (const file of readdirSync(SVG_DIR).filter((f) => f.endsWith(".svg"))) {
    const name = pascalName(file);
    if (index.has(name)) throw new Error(`${file} and ${index.get(name)} both map to ${name}`);
    index.set(name, file);
  }
  return index;
}

export function readNames(file = NAMES_FILE) {
  const names = JSON.parse(readFileSync(file, "utf8"));
  if (!Array.isArray(names) || names.some((n) => typeof n !== "string")) {
    throw new Error(`${path.basename(file)} must be a JSON array of icon names`);
  }
  return [...new Set(names)].sort();
}

export function generate(names = readNames()) {
  const index = svgIndex();
  const missing = names.filter((name) => !index.has(name));
  if (missing.length > 0) {
    throw new Error(`no SVG in @gravity-ui/icons ${GRAVITY_VERSION} for: ${missing.join(", ")}`);
  }
  const lines = [
    `// GENERATED by scripts/gen-icons.mjs from @gravity-ui/icons ${GRAVITY_VERSION} and icons.json. Do not edit:`,
    "// add the name to icons.json, then run `pnpm --filter @injishi/mobile icons:gen` (mobile spec 0002, D-n).",
    "",
    "/** A glyph on a square view box of `size` units. An `evenodd` path cuts its holes by the even odd rule. */",
    "export type IconGlyph = { size: number; paths: readonly { d: string; evenodd?: true }[] };",
    "",
    "export const iconGlyphs = {",
  ];
  for (const name of names) {
    const file = index.get(name);
    const glyph = parseSvg(readFileSync(path.join(SVG_DIR, file), "utf8"), file);
    lines.push(`  ${name}: {`, `    size: ${glyph.size},`, "    paths: [");
    // One property per line, the shape Biome keeps, so formatting the folder never makes the file stale.
    for (const p of glyph.paths) {
      lines.push(
        "      {",
        `        d: ${JSON.stringify(p.d)},`,
        ...(p.evenodd ? ["        evenodd: true,"] : []),
        "      },",
      );
    }
    lines.push("    ],", "  },");
  }
  lines.push(
    "} as const satisfies Record<string, IconGlyph>;",
    "",
    "/** Every icon name the app may use. A name outside `icons.json` fails typecheck (AC-10). */",
    "export type IconName = keyof typeof iconGlyphs;",
    "",
  );
  return lines.join("\n");
}

function sourceFiles(dir) {
  const out = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...sourceFiles(full));
    else if (/\.(ts|tsx)$/.test(entry.name) && full !== OUT_FILE) out.push(full);
  }
  return out;
}

/** Names written as `name="X"` on an icon element (`Icon`, `RowIcon`, an old screen's `IconTile`). */
export function namesInUse(files = sourceFiles(SRC_DIR)) {
  const used = new Map();
  for (const file of files) {
    const text = readFileSync(file, "utf8");
    for (const [, name] of text.matchAll(/<\w*Icon\w*\s[^>]*?\bname="([A-Za-z0-9]+)"/g)) {
      if (!used.has(name)) used.set(name, path.relative(APP_DIR, file).replaceAll("\\", "/"));
    }
  }
  return used;
}

function main() {
  const check = process.argv.includes("--check");
  const names = readNames();
  const body = generate(names);
  if (!check) {
    writeFileSync(OUT_FILE, body);
    console.log(`icons:gen wrote src/components/ui/icon-glyphs.ts (${names.length} icons).`);
    return;
  }
  const problems = [];
  let existing = null;
  try {
    existing = readFileSync(OUT_FILE, "utf8");
  } catch {
    problems.push("src/components/ui/icon-glyphs.ts is missing.");
  }
  if (existing !== null && existing.replace(/\r\n/g, "\n") !== body) {
    problems.push("src/components/ui/icon-glyphs.ts is stale against icons.json or @gravity-ui/icons.");
  }
  const listed = new Set(names);
  for (const [name, file] of namesInUse()) {
    if (!listed.has(name)) problems.push(`${file} uses the icon "${name}", which icons.json does not list.`);
  }
  if (problems.length > 0) {
    console.error(`icons:check failed:\n  ${problems.join("\n  ")}\nRun pnpm --filter @injishi/mobile icons:gen.`);
    process.exit(1);
  }
  console.log(`icons:check: icon-glyphs.ts is up to date (${names.length} icons) and every name in use is listed.`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    main();
  } catch (error) {
    console.error(`icons: ${error.message}`);
    process.exit(1);
  }
}
