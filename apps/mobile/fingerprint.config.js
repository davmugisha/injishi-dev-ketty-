// What the runtime version (the fingerprint of the app's native side, mobile spec 0001 D-o) leaves out,
// so the same commit gives the same runtime version on this Windows PC as on EAS's builders (AC-9), and
// so editing a script that never runs on the build machine does not strand installed builds (D-ab).
//
// - The version fields: raising `version` alone changes no native code, so it must not strand the
//   builds already installed.
// - The whole `scripts` section of package.json, then, hashed back as one extra source, only the
//   scripts that run on the build machine (BUILD_MACHINE_SCRIPTS): one of those could patch native
//   code, so editing it is a native change. Editing `lint`, `test` or `check:ci` is not.
// - The generated `android/` and `ios/` folders. The app is generated by prebuild (the root .gitignore
//   ignores both), but EAS uploads the project without `.git` (see .easignore), so on the builder the
//   fingerprint cannot ask git, would take the folders prebuild just wrote for committed native code,
//   and would hash them instead of the config plugins. check:ci fails if either is ever committed.
//
// @expo/fingerprint falls back to its defaults when this file throws, so check:ci asserts it loads
// with these values. Any new skip or ignore needs AC-9's cross machine test again.

const { scripts = {} } = require("./package.json");

const BUILD_MACHINE_SCRIPTS = /^(preinstall|install|postinstall|prepare|eas-build-.+)$/;

const buildScripts = Object.fromEntries(
  Object.keys(scripts)
    .filter((name) => BUILD_MACHINE_SCRIPTS.test(name))
    .sort()
    .map((name) => [name, scripts[name]]),
);

/** @type {import('@expo/fingerprint').Config} */
const config = {
  sourceSkips: ["ExpoConfigVersions", "PackageJsonScriptsAll"],
  extraSources: [
    {
      type: "contents",
      id: "packageJson:buildScripts",
      contents: JSON.stringify(buildScripts),
      reasons: ["packageJson:buildScripts"],
    },
  ],
  ignorePaths: ["android/**/*", "ios/**/*"],
};

module.exports = config;
