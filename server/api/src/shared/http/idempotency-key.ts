import {
  BadRequestException,
  ExecutionContext,
  createParamDecorator,
} from '@nestjs/common';

/** A v4-shaped UUID. Loose on the version nibble; strict on the shape. */
const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

interface RequestWithHeaders {
  headers: Record<string, string | string[] | undefined>;
}

/**
 * The client key on a command that moves money (ADR-012, AC-14).
 *
 * A front desk on a property network retries. Without a key, a retried payment
 * charges twice, which is the worst failure this system can produce: the guest
 * is out real money and the only record says both charges were legitimate.
 *
 * The key is CLIENT generated on purpose. The server cannot tell a retry from a
 * genuine second payment of the same amount a minute later, and guessing would
 * either lose a real payment or accept a duplicate. Only the caller knows which
 * it meant, so the caller says so.
 *
 * Required rather than optional on the routes that use it. An optional key is a
 * key nobody sends: the failure it prevents is rare, so a missing one is never
 * noticed until the day it matters. A command that moves money and cannot be
 * retried safely should refuse to run.
 *
 * Rejects a malformed key rather than passing it through. A key is stored under
 * a unique constraint, so accepting `"1"` or `"retry"` would let two unrelated
 * commands collide and the second silently receive the first one's result.
 */
export const IdempotencyKey = createParamDecorator(
  (_data: unknown, context: ExecutionContext): string => {
    const request = context.switchToHttp().getRequest<RequestWithHeaders>();
    const header = request.headers['idempotency-key'];
    const key = Array.isArray(header) ? header[0] : header;

    if (!key) {
      throw new BadRequestException(
        'This command needs an Idempotency-Key header so a retry cannot act twice.',
      );
    }
    if (!UUID.test(key)) {
      throw new BadRequestException(
        'Idempotency-Key must be a UUID generated by the client.',
      );
    }
    return key.toLowerCase();
  },
);
