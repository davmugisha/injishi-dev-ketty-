/**
 * Generate the photo credits page data from the image manifest.
 *
 * Twenty-four of the twenty-five photographs the site ships are CC BY or
 * CC BY-SA, which oblige us to name the author and the licence wherever the
 * work appears. Shipping them uncredited would be a licence breach, so the
 * credit list is generated from the same manifest the encoder reads — there is
 * no way to add a photograph to the site without it appearing here.
 *
 *   node scripts/generate-photo-credits.mjs
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";

const ROOT = path.resolve(import.meta.dirname, "..");
const MANIFEST = path.join(ROOT, "apps/web/public/assets/sourced/MANIFEST.json");
const OUT = path.join(ROOT, "apps/web/src/data/generated/photo-credits.ts");

const entries = JSON.parse(readFileSync(MANIFEST, "utf8"));

// Commons author fields can carry newlines and markup remnants — a derivative
// work credits both photographers on separate lines — so whitespace is
// collapsed as well as quotes escaped, or the emitted string literal breaks.
const esc = (s) =>
  String(s ?? "")
    .replace(/\s+/g, " ")
    .trim()
    .replace(/\\/g, "\\\\")
    .replace(/"/g, '\\"');

const rows = entries
  .slice()
  .sort((a, b) => a.subject.localeCompare(b.subject) || a.file.localeCompare(b.file))
  .map(
    (e) => `  {
    stem: "${esc(e.file.replace(/\.[^.]+$/, ""))}",
    subject: "${esc(e.subject)}",
    author: "${esc(e.author)}",
    licence: "${esc(e.licence)}",
    sourceUrl: "${esc(e.source_url)}",
    attributionRequired: ${e.attribution_required ? "true" : "false"},
  },`,
  )
  .join("\n");

const file = `// Generated by scripts/generate-photo-credits.mjs. Do not edit by hand.
//
// Every photograph the site ships, with the author and licence Wikimedia
// Commons publishes for it. Most are CC BY or CC BY-SA, which require the
// credit to travel with the work — so this list is generated from the image
// manifest rather than maintained separately, and a photograph cannot reach
// the site without reaching this page.

export interface PhotoCredit {
  stem: string;
  subject: string;
  author: string;
  licence: string;
  sourceUrl: string;
  attributionRequired: boolean;
}

export const PHOTO_CREDITS: PhotoCredit[] = [
${rows}
];
`;

mkdirSync(path.dirname(OUT), { recursive: true });
writeFileSync(OUT, file);

const needing = entries.filter((e) => e.attribution_required).length;
console.log(`${entries.length} credits written (${needing} require attribution).`);
