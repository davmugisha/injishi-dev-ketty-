/**
 * Encode sourced photography into the variants the site's <picture> elements ask for.
 *
 * Two conventions coexist in the components: ArtDirectedImage falls back to
 * .webp, the listing card falls back to .jpg. Rather than police which stem is
 * used where — that mismatch is exactly what produced the /assets/rwanda-*.jpg
 * 404s — every stem here ships all three formats at every width.
 *
 * Sizes are width-only. Nothing is cropped: the components use object-cover,
 * so art direction stays a CSS concern and the encoder never has to guess an
 * aspect ratio.
 *
 *   node scripts/encode-images.mjs [--force]
 *
 * Reads  apps/web/public/assets/sourced/
 * Writes apps/web/public/assets/<stem>[-<width>].{avif,webp,jpg}
 *        apps/web/src/data/generated/image-variants.json
 */
import { readdir, mkdir, stat, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import path from "node:path";
import sharp from "sharp";

const ROOT = path.resolve(import.meta.dirname, "..");
const SOURCED = path.join(ROOT, "apps/web/public/assets/sourced");
const OUT = path.join(ROOT, "apps/web/public/assets");
const GENERATED = path.join(ROOT, "apps/web/src/data/generated");

/** Widths every stem is exported at, narrowest first. The widest is unsuffixed. */
const WIDTHS = [480, 960, 1920];
const FORMATS = ["avif", "webp", "jpg"];
const FORCE = process.argv.includes("--force");

const ENCODERS = {
  avif: (img) => img.avif({ quality: 55, effort: 4 }),
  webp: (img) => img.webp({ quality: 78 }),
  jpg: (img) => img.jpeg({ quality: 80, mozjpeg: true, progressive: true }),
};

const isImage = (name) => /\.(jpe?g|png|webp|avif|tiff?)$/i.test(name);

async function main() {
  if (!existsSync(SOURCED)) {
    console.error(`No sourced directory at ${SOURCED} — nothing to encode.`);
    process.exit(1);
  }
  await mkdir(GENERATED, { recursive: true });

  const files = (await readdir(SOURCED)).filter(isImage);
  if (files.length === 0) {
    console.error("sourced/ holds no images.");
    process.exit(1);
  }

  const variants = {};
  let written = 0;
  let skipped = 0;

  for (const file of files) {
    const stem = path.basename(file, path.extname(file));
    const input = path.join(SOURCED, file);
    const meta = await sharp(input).metadata();

    // Never upscale, never exceed the widest declared size: a 900px source
    // gets 480 and 900, a 4080px source gets 480, 960 and 1920.
    const cap = Math.min(meta.width, WIDTHS.at(-1));
    const widths = [...WIDTHS.filter((w) => w < cap), cap];
    const widest = cap;
    variants[stem] = widths;

    for (const width of widths) {
      for (const format of FORMATS) {
        const suffix = width === widest ? "" : `-${width}`;
        const outPath = path.join(OUT, `${stem}${suffix}.${format}`);

        if (!FORCE && existsSync(outPath)) {
          const [src, dst] = await Promise.all([stat(input), stat(outPath)]);
          if (dst.mtimeMs > src.mtimeMs) { skipped++; continue; }
        }

        const pipeline = ENCODERS[format](
          sharp(input).resize({ width, withoutEnlargement: true }),
        );
        await pipeline.toFile(outPath);
        written++;
      }
    }
    console.log(`${stem}  ${meta.width}x${meta.height}  ->  ${widths.join(", ")}`);
  }

  // Emitted as TypeScript rather than JSON so it imports without
  // resolveJsonModule and keeps its type through the build.
  const body = Object.entries(variants)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([stem, widths]) => `  ${JSON.stringify(stem)}: [${widths.join(", ")}],`)
    .join("\n");

  await writeFile(
    path.join(GENERATED, "image-variants.ts"),
    `// Generated by scripts/encode-images.mjs. Do not edit by hand.\n` +
      `// Widths actually exported for each stem, narrowest first.\n` +
      `export const IMAGE_VARIANTS: Record<string, number[]> = {\n${body}\n};\n`,
  );

  console.log(`\n${files.length} sources, ${written} files written, ${skipped} up to date.`);
  console.log(`Variant map: apps/web/src/data/generated/image-variants.ts`);
}

await main();
