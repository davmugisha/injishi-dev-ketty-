import type { ProductDefinition } from "@injishi/product-contract";

/**
 * Injishi PMS (ADR-074): what it is, and the shapes its views draw.
 *
 * Each module names the permissions its API routes declare (the `ops` PMS and listing setup controllers), so an
 * app shows the module when the workspace grant holds any one of them. That is an affordance only: the API
 * refuses what the grant does not hold. The guest's own phone screens (trip, stay, key, bill, requests) belong to
 * these modules too and sit behind a session alone (`/api/v1/me`), because a guest holds no workspace.
 *
 * Three modules are *Horizon*. Two have no route of their own yet, so each names the permission of the routes it
 * would extend and nobody without it is shown a sample: loyalty the stay offers (`offer.manage`), groups and
 * packages the rate plans (`listing.manage`). Lost and found has routes of its own (`lostfound.manage`).
 */
export const definition = {
  id: "pms",
  name: "Injishi PMS",
  surfaces: ["web"],
  modules: [
    {
      id: "reservations",
      surfaces: ["web"],
      permissions: ["reservation.approve", "reservation.assign", "stay.checkin", "money.view"],
    },
    {
      id: "front-desk",
      surfaces: ["web"],
      permissions: ["reservation.approve", "reservation.assign", "stay.checkin", "stay.checkout", "money.view"],
    },
    { id: "stays-and-guests", surfaces: ["web"], permissions: ["stay.checkin", "stay.checkout"] },
    {
      id: "folios-and-night-audit",
      surfaces: ["web"],
      permissions: ["folio.charge", "folio.payment", "folio.close", "money.view"],
    },
    { id: "housekeeping", surfaces: ["web"], permissions: ["housekeeping.set", "task.assign"] },
    { id: "rates-and-availability", surfaces: ["web"], permissions: ["listing.manage"] },
    { id: "stay-setup", surfaces: ["web"], permissions: ["listing.manage", "amenity.manage"] },
    { id: "guest-requests", surfaces: ["web"], permissions: ["message.send"] },
    { id: "maintenance", surfaces: ["web"], permissions: ["ticket.advance"] },
    { id: "loyalty", surfaces: ["web"], permissions: ["offer.manage"] },
    { id: "lost-and-found", surfaces: ["web"], permissions: ["lostfound.manage"] },
    { id: "groups-and-packages", surfaces: ["web"], permissions: ["listing.manage"] },
  ],
} as const satisfies ProductDefinition<"pms">;

